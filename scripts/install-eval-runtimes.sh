#!/usr/bin/env bash
#
# Installs the interpreters `eval_code` can drive into a distrobox container and
# exports them onto the host PATH as thin wrappers.
#
# This exists because the host is an immutable/atomic system where installing
# toolchains directly is undesirable. Everything lives in one container and is
# reached through a wrapper script per binary, matching how `node` was already
# set up here.
#
# Re-running is safe: apt skips what is present and wrappers are overwritten.
set -euo pipefail

CONTAINER="${OMNI_EVAL_CONTAINER:-build-box}"
BIN_DIR="${OMNI_EVAL_BIN_DIR:-$HOME/.local/bin}"

usage() {
    cat <<USAGE
Usage: ${0##*/} [--list] [--dry-run]

  --list      Show which runtimes are present on the host and exit.
  --dry-run   Print what would be installed without changing anything.

Environment:
  OMNI_EVAL_CONTAINER   distrobox container to install into (default: build-box)
  OMNI_EVAL_BIN_DIR     where to write host wrappers (default: ~/.local/bin)
USAGE
}

# Debian packages that provide a genuine implementation, and the binary each
# one exposes. Order is install-cost ascending; ghc is by far the largest.
#
# Deliberately excluded:
#   swift    Debian's `swift` is the OpenStack object-storage client, NOT the
#            Swift compiler. Installing it would make eval_code "support" swift
#            while running entirely unrelated software.
#   scala    2.11.12 (2015). Too old to run modern scripts.
#   kotlin   1.3.31 (2019), and kotlinc script startup is tens of seconds.
#   julia, zig, dart, powershell
#            Not packaged for Debian; install upstream if you want them.
APT_RUNTIMES=(
    "ruby:ruby"
    "lua5.4:lua"
    "gfortran:gfortran"
    "ocaml:ocaml"
    "elixir:elixir"
    "r-base-core:Rscript"
    "ghc:runghc"
)

# Installed with npm inside the container rather than apt.
NPM_RUNTIMES=("tsx:tsx")

list_status() {
    echo "runtime availability on the host:"
    for entry in "${APT_RUNTIMES[@]}" "${NPM_RUNTIMES[@]}"; do
        local binary="${entry#*:}"
        printf '  %-10s ' "$binary"
        if command -v "$binary" >/dev/null 2>&1; then
            echo "present  ($(command -v "$binary"))"
        else
            echo "absent"
        fi
    done
}

write_wrapper() {
    local name="$1" target="$2"
    cat > "$BIN_DIR/$name" <<WRAPPER
#!/bin/bash
# Generated by scripts/install-eval-runtimes.sh — runs $name inside $CONTAINER.
PATH="/usr/bin:/bin:/usr/local/bin:\$PATH"
exec /usr/bin/distrobox enter $CONTAINER -- $target "\$@"
WRAPPER
    chmod +x "$BIN_DIR/$name"
}

dry_run=false
for arg in "$@"; do
    case "$arg" in
        --list) list_status; exit 0 ;;
        --dry-run) dry_run=true ;;
        --help | -h) usage; exit 0 ;;
        *) echo "unknown argument: $arg" >&2; usage >&2; exit 2 ;;
    esac
done

if ! command -v distrobox >/dev/null 2>&1; then
    echo "error: distrobox is not installed" >&2
    exit 1
fi

if ! distrobox list 2>/dev/null | grep -q "\b$CONTAINER\b"; then
    echo "error: container '$CONTAINER' does not exist; create it first" >&2
    exit 1
fi

packages=()
for entry in "${APT_RUNTIMES[@]}"; do
    packages+=("${entry%%:*}")
done

if [ "$dry_run" = true ]; then
    echo "would install into $CONTAINER: ${packages[*]}"
    echo "would npm install -g: tsx"
    echo "would write wrappers to $BIN_DIR"
    exit 0
fi

echo "==> installing into $CONTAINER (ghc is large; this can take a while)"
distrobox enter "$CONTAINER" -- sh -c \
    "sudo apt-get update -qq && sudo apt-get install -y -qq ${packages[*]}"

echo "==> installing npm runtimes"
distrobox enter "$CONTAINER" -- sh -c "sudo npm install -g ${NPM_RUNTIMES[*]%%:*}" || \
    echo "warning: npm install failed; typescript will be unavailable"

echo "==> writing host wrappers to $BIN_DIR"
mkdir -p "$BIN_DIR"
for entry in "${APT_RUNTIMES[@]}"; do
    binary="${entry#*:}"
    case "$binary" in
        lua) write_wrapper lua /usr/bin/lua5.4 ;;
        *) write_wrapper "$binary" "/usr/bin/$binary" ;;
    esac
done
write_wrapper tsx /usr/local/bin/tsx

echo
list_status
echo
echo "Verify with: cargo test --lib eval -- --nocapture"

case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) echo "note: $BIN_DIR is not on your PATH" ;;
esac
